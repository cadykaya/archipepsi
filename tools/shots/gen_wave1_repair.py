"""Focused before/after views of the eight repaired Wave 1 points.

    python3 tools/shots/gen_wave1_repair.py
    tools/shoot.sh tools/shots/wave1_repair.json docs/art/review/wave1_repair

The repair moved DECLARED POINTS and no geometry, so these compose the
`wave1_*` overlay figures over the real shells: red where a point was,
green where it is, grey for the block or ring it belongs to. See
`tools/blender/build_wave1_repair_overlay.py` for why both ends are
derived rather than typed.

CAMERA FRAME is the package's, unchanged (L-52): a Godot point negated in
x and z, yaw theta looks along `(sin theta, 0, cos theta)`, `eye` adds an
eye height `look` does not.

Each camera stands on the side the stance moved TOWARD, so the green pin
is in front and the red one is behind it, inside the block -- which is
the whole point of the picture.
"""

import json
import math
import pathlib

EYE = 1.6
LIGHT = {"ambient": 0.30, "key_energy": 1.10}
SHELL = "model:batch040/shells/%s.glb"
OV = "batch040/overlays/%s.glb"


def R(x, y, z):
    return [round(-x, 3) + 0.0, round(y, 3) + 0.0, round(-z, 3) + 0.0]


def aim(eye_r, at_r, lift=EYE):
    dx = at_r[0] - eye_r[0]
    dy = at_r[1] - (eye_r[1] + lift)
    dz = at_r[2] - eye_r[2]
    yaw = math.degrees(math.atan2(dx, dz)) % 360.0
    flat = math.hypot(dx, dz)
    return round(yaw, 1), round(math.degrees(math.atan2(dy, flat))
                                if flat > 1e-6 else 0.0, 1)


def shot(key, shell, figure, stand, look_at, title, note):
    eye_r, at_r = R(*stand), R(*look_at)
    yaw, pitch = aim(eye_r, at_r)
    return {"name": key,
            "scene": "%s + %s@0,0,0" % (SHELL % shell, OV % figure),
            "eye": eye_r, "yaw": yaw, "pitch": pitch, "light": LIGHT,
            "caption": [title, note]}


shots = [
    shot("W1_yard_cover", "shell_yard_gantry", "wave1_cover_yard",
         (-34.0, 7.0, 6.0), (-26.0, 1.0, 15.0),
         "YARD  COVER_0  RED WAS INSIDE THE BLOCK, GREEN IS BESIDE IT",
         "all four yard stances moved the same way, 2.6 to 3.6 m"),
    shot("W1_yard_wide", "shell_yard_gantry", "wave1_cover_yard",
         (0.0, 13.0, 26.0), (-6.0, 0.5, 24.0),
         "YARD  ALL FOUR COVER CLUSTERS FROM THE CRANE",
         "the blocks did not move; only the declared stances did"),
    shot("W1_span_cover", "shell_span_basin", "wave1_cover_span",
         (-14.0, 6.0, 13.0), (-10.5, 1.0, 22.0),
         "SPAN  COVER_0  THE SAME DEFECT, THE SAME REPAIR",
         "the span is long in z, so its stances step in x"),
    shot("W1_plenum_reward", "shell_plenum_helix", "wave1_reward",
         (8.5, 31.5, 15.5), (2.0, 29.2, 10.5),
         "PLENUM  THE REWARD WAS INSIDE THE MACHINE",
         "green is the band; the red pin is behind it, inside the machine"),
]

main = {
    "_comment": [
        "WAVE 1 REPAIR -- the eight Art-owned findings, before and after.",
        "GENERATED by tools/shots/gen_wave1_repair.py; edit that.",
        "",
        "Production measured 2 findings on the plenum, 5 on the yard and",
        "4 on the span. THREE of the eleven are the audit assuming a",
        "room's entry is its local origin; under the owner's ruling those",
        "are superseded and the rooms are deliberately unchanged. The",
        "other EIGHT were Art's, and all eight were one mistake: a",
        "declared point carrying the CENTRE of the thing it names.",
        "",
        "No geometry moved. All three shells export the same triangle and",
        "collider counts, and all three stay review: 'pending'.",
    ],
    "defaults": {"size": [1920, 1080], "backdrop": "none", "game_lens": True},
    "shots": shots,
}

out = pathlib.Path("tools/shots/wave1_repair.json")
out.write_text(json.dumps(main, indent=2) + "\n")
print("wrote", out, "with", len(shots), "shots")
