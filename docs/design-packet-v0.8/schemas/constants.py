# --------------------------------------------------------------------------
# The goal reservation — ONE definition, used by every path
# --------------------------------------------------------------------------
# v0.5 stated "Check 030 is never shop stock, never a normal Zone reward" in
# five prose locations and enforced it in exactly one model validator, on the
# Zone path. Shop stock, the purchase intent and the pending-transaction
# record all accepted it, so `6 coins -> buy Check 030 -> win` was a legal
# message sequence. The rule now lives here and every reservation-capable
# field derives from it, so a neighbouring path cannot diverge again.

#: The goal is deliberately the LAST location id. That makes "any location
#: except the goal" a plain closed range, which is expressible in JSON Schema
#: and GDScript rather than only in a Python validator — so the constraint
#: survives export to the provider schema and to the engine. If the goal ever
#: moves off the end, this assert fires instead of the range silently
#: admitting Check 030 again.
