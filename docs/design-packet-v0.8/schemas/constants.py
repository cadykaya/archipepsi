def prng_seed(*parts: object) -> int:
    """Stable 64-bit seed from a campaign key.

    Never use Python's built-in hash(): it is randomized per process.
    """
    key = "|".join(str(p) for p in parts)
    return int.from_bytes(hashlib.sha256(key.encode("utf-8")).digest()[:8], "big")


def deterministic_shuffle(items: list, *seed_parts: object) -> list:
    """Fisher-Yates over a seeded Mersenne Twister. Returns a new list.

    Descending index, j = rng.randrange(i + 1). Any reimplementation must
    match exactly, including loop direction. Pinned by test.
    """
    rng = random.Random(prng_seed(*seed_parts))
    out = list(items)
    for i in range(len(out) - 1, 0, -1):
        j = rng.randrange(i + 1)
        out[i], out[j] = out[j], out[i]
    return out


def track_order_seed(seed_name: str, team: int, slot_id: int) -> tuple:
    return (seed_name, team, slot_id, "track_order")


def zone_selection_seed(seed_name: str, team: int, slot_id: int,
                        generation_counter: int, target_game: str) -> tuple:
    """Same tuple shape as track_order_seed plus the per-Zone discriminators.

    v0.4 dropped `team` here, so two slots on different teams with the same
    slot_id got identical Zone shuffles.
    """
    return (seed_name, team, slot_id, generation_counter, target_game)
